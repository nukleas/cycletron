/// Decode a hex string into binary onsets, 4 bits per digit, MSB first.
/// e.g. "a4" → 1010 0100.
pub fn hex_beat(hex: &str) -> Result<Vec<bool>, String> {
    let mut bits = Vec::with_capacity(hex.len() * 4);
    for ch in hex.chars() {
        let nibble = ch
            .to_digit(16)
            .ok_or_else(|| format!("'{ch}' is not a hex digit"))?;
        for shift in (0..4).rev() {
            bits.push((nibble >> shift) & 1 == 1);
        }
    }
    Ok(bits)
}

/// Render a hex-beat drum pattern as a `.strudel` document.
pub fn hexbeat(hex: &str) -> Result<String, String> {
    let bits = hex_beat(hex)?;
    if !bits.iter().any(|&b| b) {
        return Err(format!("hex {hex:?} has no onsets — would be silent"));
    }
    let steps = bits
        .iter()
        .map(|&b| if b { "bd" } else { "~" })
        .collect::<Vec<_>>()
        .join(" ");
    let binary = bits
        .iter()
        .map(|&b| if b { '1' } else { '0' })
        .collect::<String>();
    Ok(format!(
        "// Hex beat \"{hex}\": each hex digit is four binary steps, 1 = kick onset.\n\
         // {hex} → {binary} ({} steps). A compact way to notate a whole bar of\n\
         // rhythm as a short string. Steady hats sit underneath for pulse.\n\
         setbpm(120);\n\
         \n\
         stack(\n\
         \x20 s(\"{steps}\"),\n\
         \x20 s(\"hh*8\").gain(0.45)\n\
         )\n",
        bits.len()
    ))
}

// ---------------------------------------------------------------------------
// harmony — Roman numerals → diatonic chords
// ---------------------------------------------------------------------------

/// Major-scale semitone offsets and the diatonic triad quality on each degree.
const MAJOR_DEGREES: [(i32, Quality); 7] = [
    (0, Quality::Maj),
    (2, Quality::Min),
    (4, Quality::Min),
    (5, Quality::Maj),
    (7, Quality::Maj),
    (9, Quality::Min),
    (11, Quality::Dim),
];

#[derive(Clone, Copy, PartialEq, Debug)]
enum Quality {
    Maj,
    Min,
    Dim,
}

impl Quality {
    fn suffix(self) -> &'static str {
        match self {
            Quality::Maj => "",
            Quality::Min => "m",
            Quality::Dim => "dim",
        }
    }
}

/// Parse a key root (e.g. "C", "F#", "Bb") into a pitch class 0..12.
pub fn parse_key(key: &str) -> Result<i32, String> {
    let mut chars = key.chars();
    let letter = chars.next().ok_or("empty key")?;
    let base = match letter.to_ascii_uppercase() {
        'C' => 0,
        'D' => 2,
        'E' => 4,
        'F' => 5,
        'G' => 7,
        'A' => 9,
        'B' => 11,
        other => return Err(format!("'{other}' is not a note letter")),
    };
    let acc: i32 = match chars.next() {
        Some('#') => 1,
        Some('b') => -1,
        None => 0,
        Some(other) => return Err(format!("'{other}' is not an accidental")),
    };
    Ok((base + acc).rem_euclid(12))
}

/// Parse a Roman numeral (I..VII, any case, optional °/o) to a degree index 0..7.
fn numeral_to_degree(token: &str) -> Result<usize, String> {
    let core: String = token
        .chars()
        .filter(|c| c.is_ascii_alphabetic())
        .map(|c| c.to_ascii_uppercase())
        .collect();
    match core.as_str() {
        "I" => Ok(0),
        "II" => Ok(1),
        "III" => Ok(2),
        "IV" => Ok(3),
        "V" => Ok(4),
        "VI" => Ok(5),
        "VII" => Ok(6),
        other => Err(format!("'{other}' is not a Roman numeral I–VII")),
    }
}

/// Map a numeral progression in a major key to `chord(...)` symbols (e.g. "Dm").
pub fn numerals_to_chords(key_pc: i32, numerals: &str) -> Result<Vec<String>, String> {
    numerals
        .split_whitespace()
        .map(|tok| {
            let degree = numeral_to_degree(tok)?;
            let (offset, quality) = MAJOR_DEGREES[degree];
            let root = PC_UPPER[(key_pc + offset).rem_euclid(12) as usize];
            Ok(format!("{root}{}", quality.suffix()))
        })
        .collect()
}

/// Render a Roman-numeral chord progression as a `.strudel` document.
pub fn numerals(key: &str, numerals: &str) -> Result<String, String> {
    let key_pc = parse_key(key)?;
    let chords = numerals_to_chords(key_pc, numerals)?;
    let symbols = chords.join(" ");
    let key_name = PC_UPPER[key_pc as usize];
    Ok(format!(
        "// Diatonic triads from Roman numerals in {key_name} major: {numerals} → {symbols}.\n\
         // One chord per cycle via slowcat <...>. Quality follows the major scale\n\
         // (I,IV,V major; ii,iii,vi minor; vii° diminished).\n\
         setbpm(90);\n\
         \n\
         chord(\"<{symbols}>\")\n\
         \x20 .s(\"sawtooth\")\n\
         \x20 .cutoff(1200)\n\
         \x20 .attack(0.05)\n\
         \x20 .release(0.6)\n\
         \x20 .gain(0.55)\n"
    ))
}

