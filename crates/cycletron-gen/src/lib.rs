/// Mirror a motif into a palindrome, reflecting around the final element so
/// it is not duplicated: [a b c d] → [a b c d c b a].
pub fn palindrome_tokens(motif: &[String]) -> Vec<String> {
    let mut out = motif.to_vec();
    out.extend(motif.iter().rev().skip(1).cloned());
    out
}

/// Render a palindromic motif as a `.strudel` document.
pub fn palindrome(motif: &str) -> String {
    let tokens: Vec<String> = motif.split_whitespace().map(String::from).collect();
    let mirrored = palindrome_tokens(&tokens).join(" ");
    format!(
        "// Palindromic motif: the phrase reads the same forwards and backwards.\n\
         // Base motif \"{motif}\" reflected around its last note — a symmetric\n\
         // arch form. Mirroring is one of total-serialism's transforms.\n\
         setbpm(96);\n\
         \n\
         note(\"{mirrored}\")\n\
         \x20 .s(\"triangle\")\n\
         \x20 .attack(0.01)\n\
         \x20 .release(0.3)\n\
         \x20 .gain(0.6)\n"
    )
}

// ---------------------------------------------------------------------------
// motion — elementary cellular automaton
// ---------------------------------------------------------------------------

/// Evolve an elementary cellular automaton (Wolfram numbering) from a single
/// centre seed, wrapping at the edges. Returns `gens` rows of `width` cells.
pub fn ca_rows(rule: u8, width: usize, gens: usize) -> Vec<Vec<bool>> {
    let mut row = vec![false; width];
    row[width / 2] = true;
    let mut rows = Vec::with_capacity(gens);
    for _ in 0..gens {
        rows.push(row.clone());
        let mut next = vec![false; width];
        for i in 0..width {
            let l = row[(i + width - 1) % width];
            let c = row[i];
            let r = row[(i + 1) % width];
            let idx = (l as u8) << 2 | (c as u8) << 1 | (r as u8);
            next[i] = (rule >> idx) & 1 == 1;
        }
        row = next;
    }
    rows
}

/// Render a cellular-automaton-driven evolving rhythm as a `.strudel` document.
pub fn automaton(rule: u8, width: usize, gens: usize) -> Result<String, String> {
    if width == 0 || gens == 0 {
        return Err("width and gens must be > 0".to_string());
    }
    let rows = ca_rows(rule, width, gens);
    if rows.first().is_none_or(|r| !r.iter().any(|&c| c)) {
        return Err("seed row is silent".to_string());
    }
    // Each row becomes a bracketed step group; slowcat them so the rhythm
    // reorganises every cycle.
    let groups = rows
        .iter()
        .map(|row| {
            let steps = row
                .iter()
                .map(|&c| if c { "hh" } else { "~" })
                .collect::<Vec<_>>()
                .join(" ");
            format!("[{steps}]")
        })
        .collect::<Vec<_>>()
        .join(" ");
    Ok(format!(
        "// Elementary cellular automaton (Wolfram rule {rule}) drives an evolving\n\
         // hat line. A single seed cell evolves over {gens} generations; each row\n\
         // becomes one cycle, so the rhythm reorganises itself every bar.\n\
         setbpm(120);\n\
         \n\
         stack(\n\
         \x20 s(\"bd*4\"),\n\
         \x20 s(\"<{groups}>\").gain(0.5)\n\
         )\n"
    ))
}

// ---------------------------------------------------------------------------

fn join_ints(xs: &[i32]) -> String {
    xs.iter()
        .map(|n| n.to_string())
        .collect::<Vec<_>>()
        .join(" ")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn infinity_matches_known_prefix() {
        assert_eq!(
            infinity_series(16),
            vec![0, 1, -1, 2, 1, 0, -2, 3, -1, 2, 0, 1, 2, -1, -3, 4]
        );
    }

    #[test]
    fn infinity_even_indices_are_inverted_whole() {
        let a = infinity_series(16);
        for n in 0..8 {
            assert_eq!(a[2 * n], -a[n]);
        }
    }

    #[test]
    fn lowering_spells_root_and_offsets() {
        assert_eq!(
            offsets_to_notes(&[0, 1, -1, 4], 60),
            vec!["c4", "c#4", "b3", "e4"]
        );
    }

    #[test]
    fn hex_beat_decodes_nibbles_msb_first() {
        assert_eq!(
            hex_beat("a4").unwrap(),
            vec![true, false, true, false, false, true, false, false]
        );
    }

    #[test]
    fn numerals_resolve_diatonic_qualities_in_c() {
        let chords = numerals_to_chords(parse_key("C").unwrap(), "ii V I vi").unwrap();
        assert_eq!(chords, vec!["Dm", "G", "C", "Am"]);
    }

    #[test]
    fn numerals_transpose_to_other_keys() {
        let chords = numerals_to_chords(parse_key("G").unwrap(), "ii V I").unwrap();
        assert_eq!(chords, vec!["Am", "D", "G"]);
    }

    #[test]
    fn palindrome_reflects_around_last_element() {
        let motif: Vec<String> = ["a", "b", "c", "d"].iter().map(|s| s.to_string()).collect();
        assert_eq!(
            palindrome_tokens(&motif),
            vec!["a", "b", "c", "d", "c", "b", "a"]
        );
    }

    #[test]
    fn rule90_seed_row_fans_out() {
        let rows = ca_rows(90, 8, 4);
        assert_eq!(rows[0].iter().filter(|&&c| c).count(), 1);
        assert_eq!(rows[1].iter().filter(|&&c| c).count(), 2);
    }

    #[test]
    fn rendered_documents_have_setbpm_and_body() {
        for doc in [
            infinity(16, 60),
            hexbeat("a4f2").unwrap(),
            numerals("C", "ii V I vi").unwrap(),
            palindrome("c4 e4 g4 b4"),
            automaton(90, 8, 4).unwrap(),
        ] {
            assert!(doc.contains("setbpm("), "missing setbpm: {doc}");
        }
    }
}
