/// Lowercase pitch-class names with sharps — strudel-rs note grammar (C4 = 60).
const PC_LOWER: [&str; 12] = [
    "c", "c#", "d", "d#", "e", "f", "f#", "g", "g#", "a", "a#", "b",
];
/// Uppercase pitch classes for `chord(...)` roots.
const PC_UPPER: [&str; 12] = [
    "C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B",
];

// ---------------------------------------------------------------------------
// melody — Per Nørgård's infinity series
// ---------------------------------------------------------------------------

/// Per Nørgård's *infinity series*: a(0)=0, a(2n)=-a(n), a(2n+1)=a(n)+1.
/// A fractal sequence of semitone offsets — every other term reproduces the
/// whole line transposed.
pub fn infinity_series(count: usize) -> Vec<i32> {
    let mut a: Vec<i32> = Vec::with_capacity(count);
    for n in 0..count {
        let v = if n == 0 {
            0
        } else if n % 2 == 0 {
            -a[n / 2]
        } else {
            a[n / 2] + 1
        };
        a.push(v);
    }
    a
}

/// Lower semitone offsets to strudel note tokens relative to a root MIDI number.
pub fn offsets_to_notes(series: &[i32], root: i32) -> Vec<String> {
    series
        .iter()
        .map(|&off| {
            let midi = root + off;
            let name = PC_LOWER[midi.rem_euclid(12) as usize];
            let octave = midi.div_euclid(12) - 1;
            format!("{name}{octave}")
        })
        .collect()
}

/// Render an infinity-series melody as a `.strudel` document.
pub fn infinity(count: usize, root: i32) -> String {
    let series = infinity_series(count);
    let offsets = join_ints(&series);
    let pattern = offsets_to_notes(&series, root).join(" ");
    format!(
        "// Per Nørgård's \"infinity series\" (uendelighedsrækken) — a self-similar melody.\n\
         // Recurrence: a(0)=0, a(2n) = -a(n), a(2n+1) = a(n)+1, read as semitone\n\
         // offsets from a root. The line is fractal: every other note reproduces\n\
         // the whole series transposed.\n\
         // Generated by cycletron-gen (see _references/03). Offsets: {offsets}\n\
         setbpm(96);\n\
         \n\
         note(\"{pattern}\")\n\
         \x20 .s(\"triangle\")\n\
         \x20 .attack(0.01)\n\
         \x20 .release(0.3)\n\
         \x20 .gain(0.65)\n"
    )
}

