//! `cycletron-gen` — corpus generators built from algorithmic-composition
//! primitives mined from the live-coding ecosystem (see `_references/`).
//!
//! Each generator is a pure function over integer/boolean value series; the
//! only strudel-specific step is *lowering* the series to a `.strudel` document
//! in the corpus house style. Keeping the generative core pure means it backs
//! both the `gen-pattern` CLI (offline corpus growth) and the agent's
//! `generate_pattern` tool, with one implementation. Everything emitted here is
//! designed to pass `validate_code` / `corpus-check`.
//!
//! Public entry points return a complete, ready-to-play `.strudel` document:
//!   [`infinity`]   melody   Per Nørgård's self-similar series
//!   [`hexbeat`]    rhythm   hex string → binary kick onsets
//!   [`numerals`]   harmony  Roman-numeral progression → diatonic chords
//!   [`palindrome`] form     mirror a motif into a symmetric phrase
//!   [`automaton`]  motion   elementary cellular automaton → evolving rhythm

